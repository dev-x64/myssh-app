/** Each tool's subcommands, in the order they are offered: by name. */
export const SUBCOMMANDS: Record<string, Subcommand[]> = Object.fromEntries(
  Object.entries(TABLE).map(([tool, list]) => [tool, [...list].sort((a, b) => a.name.localeCompare(b.name))]),
);

/**
 * The subcommands that could be what the line's last word is meant to be,
 * when the words before it name a tool. `typed`: that last word, empty
 * when the line ends with a space. `null` when the line is not at a
 * subcommand.
 */
export function subcommandsAt(input: string): { typed: string; found: Subcommand[] } | null {
  const words = input.replace(/^sudo\s+/, "").split(/\s+/);
  const typed = words.pop() ?? "";
  const list = SUBCOMMANDS[words.join(" ")];
  if (!list) return null;
  return { typed, found: list.filter((sub) => sub.name.startsWith(typed) && sub.name !== typed) };
}
