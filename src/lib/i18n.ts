/** A piece of wording as it reads on Windows. */
export function forWindows(locale: Locale, key: MessageKey, text: string): string {
  const whole = WINDOWS_TEXT[locale][key];
  if (whole !== undefined) return whole;
  return WINDOWS_WORDS[locale].reduce((said, [what, instead]) => said.replace(what, instead), text);
}

if (WINDOWS) {
  for (const locale of Object.keys(dictionaries) as Locale[]) {
    const words = dictionaries[locale];
    for (const key of Object.keys(words) as MessageKey[]) words[key] = forWindows(locale, key, words[key]);
  }
}

type Vars = Record<string, string | number>;

function pluralIndex(locale: Locale, n: number): number {
  if (locale === "ru") {
    const mod10 = n % 10;
    const mod100 = n % 100;
    if (mod10 === 1 && mod100 !== 11) return 0;
    if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return 1;
    return 2;
  }
  return n === 1 ? 0 : 1;
}

/**
 * Looks up a message. `{name}` placeholders are filled from `vars`; a message
 * with `|`-separated forms picks one by `vars.n`.
 */
export function translate(locale: Locale, key: MessageKey, vars?: Vars): string {
  let text = dictionaries[locale][key] ?? en[key] ?? key;
  if (text.includes("|") && vars && typeof vars.n === "number") {
    const forms = text.split("|");
    text = forms[Math.min(pluralIndex(locale, vars.n), forms.length - 1)];
  }
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.split(`{${name}}`).join(String(value));
    }
  }
  return text;
}

export type T = (key: MessageKey, vars?: Vars) => string;

export function useT(): T {
  const locale = useSettings((s) => s.locale);
  return (key, vars) => translate(locale, key, vars);
}

/** For code outside React. */
export function t(key: MessageKey, vars?: Vars): string {
  return translate(useSettings.getState().locale, key, vars);
}

