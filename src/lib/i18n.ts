export function errorText(error: { code: string; message: string }): string {
  const key = `error.${error.code}` as MessageKey;
  // Validation messages are already specific; show them as they are.
  if (error.code === "invalid" || !(key in en)) return error.message;
  return translate(useSettings.getState().locale, key);
}

export function formatSize(bytes: number, locale: Locale): string {
  const units = locale === "ru" ? ["Б", "КБ", "МБ", "ГБ", "ТБ"] : ["B", "KB", "MB", "GB", "TB"];
  let value = bytes;
  let unit = 0;
  while (value >= 1024 && unit < units.length - 1) {
    value /= 1024;
    unit += 1;
  }
  const digits = unit === 0 || value >= 100 ? 0 : 1;
  return `${value.toLocaleString(locale === "ru" ? "ru-RU" : "en-US", {
    minimumFractionDigits: digits,
    maximumFractionDigits: digits,
  })} ${units[unit]}`;
}

export function formatDateTime(seconds: number, locale: Locale): string {
  return new Date(seconds * 1000).toLocaleString(locale === "ru" ? "ru-RU" : "en-US", {
    year: "numeric",
    month: "short",
    day: "numeric",
    hour: "2-digit",
    minute: "2-digit",
  });
}

/** A moment (Unix milliseconds) relative to now: "just now", "5 min ago". */
/**
 * How long ago something was. `exact` counts the seconds of the first
 * minute, for a place that is watched as it ticks; otherwise anything
 * under a minute is "now".
 */
export function formatAgo(ms: number, locale: Locale, exact = false): string {
  const seconds = Math.round((ms - Date.now()) / 1000);
  const format = new Intl.RelativeTimeFormat(locale === "ru" ? "ru-RU" : "en-US", { numeric: "auto" });
  if (exact && Math.abs(seconds) < 60) return format.format(Math.min(seconds, 0), "second");
  if (Math.abs(seconds) < 45) return format.format(0, "second");
  if (Math.abs(seconds) < 3600) return format.format(Math.round(seconds / 60), "minute");
  if (Math.abs(seconds) < 86400) return format.format(Math.round(seconds / 3600), "hour");
  return format.format(Math.round(seconds / 86400), "day");
}

/** A moment as the clock shows it, with the day in front when it is not today. */
export function formatClock(ms: number, locale: Locale): string {
  const at = new Date(ms);
  const tag = locale === "ru" ? "ru-RU" : "en-US";
  const time = at.toLocaleTimeString(tag, { hour: "2-digit", minute: "2-digit" });
  return at.toDateString() === new Date().toDateString()
    ? time
    : `${at.toLocaleDateString(tag, { day: "numeric", month: "short" })} ${time}`;
}

export function formatDate(ms: number, locale: Locale): string {
  return new Date(ms).toLocaleDateString(locale === "ru" ? "ru-RU" : "en-US", {
    year: "numeric",
    month: "short",
    day: "numeric",
  });
}
