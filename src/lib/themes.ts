export function resolveTermTheme(id: string, appDark: boolean): TermTheme {
  if (id !== "auto") {
    const found = TERM_THEMES.find((t) => t.id === id);
    if (found) return found;
  }
  return TERM_THEMES[appDark ? 0 : 1];
}
